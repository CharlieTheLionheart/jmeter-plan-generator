"""Top-level JMX skeleton generator facade."""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional

from config_parser.models import (
    TestConfig,
)

from jmx_skeleton_generator.generators.assembler import (
    JMXAssembler,
    JMXWriter,
    JmxGenerationError,
)
from jdbc_datasource import JDBCDataSourceGenerator
from jmx_skeleton_generator.generators.ddl_setup import generate_ddl_setup_thread_group
from jmx_skeleton_generator.generators.query_groups import generate_query_thread_groups
from jmx_skeleton_generator.generators.shared_memory_setup import generate_shared_memory_setup_thread_group
from jmx_skeleton_generator.generators.test_plan import (
    generate_test_plan,
    generate_user_defined_variables,
)
from jmx_skeleton_generator.generators.write_groups import generate_write_thread_groups


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

class JMXSkeletonGenerator:
    """Generate a JMeter TestPlan JMX skeleton from configuration.

    This generator creates the JMX XML structure (TestPlan, ThreadGroups,
    hashTree hierarchy) but leaves JDBCSampler query content as placeholders
    for the ``direct-insert-write`` and ``query-functionality`` modules to fill.

    Parameters
    ----------
    test_config:
        The parsed test configuration.
    ddl_statements:
        DDL SQL strings to execute in the SetupThreadGroup.
    prepared_templates:
        Dictionary mapping ``db.table`` to INSERT template strings.
    seed_csv_paths:
        Mapping of ``db_name → {table_name → csv_file_path}`` for shared
        memory initialization.  Example:
        ``{"tsdb": {"t_table": "seeds/tsdb/t_table.csv"}}``.
    output_dir:
        Directory to write the generated ``.jmx`` file.
    """

    def __init__(
        self,
        test_config: TestConfig,
        ddl_statements: Optional[List[str]] = None,
        prepared_templates: Optional[Dict[str, str]] = None,
        seed_csv_paths: Optional[Dict[str, Dict[str, str]]] = None,
        output_dir: str = ".",
    ):
        self.test_config = test_config
        self.ddl_statements = ddl_statements or []
        self.prepared_templates = prepared_templates or {}
        self.seed_csv_paths = seed_csv_paths or {}
        self.output_dir = output_dir

    def generate(self) -> Path:
        """Assemble and write the JMX skeleton.

        Returns
        -------
        Absolute path to the written ``.jmx`` file.

        Raises
        ------
        JmxGenerationError
            When assembly or writing fails.
        """
        # 1. TestPlan + its hashTree
        tp_elements = generate_test_plan(comments="Auto-generated by kwjdbc-svt")
        tp_elem, tp_hash = tp_elements[0], tp_elements[1]

        # 2. User-defined variables from conn_config
        udv_elements = generate_user_defined_variables(self.test_config.conn_config)

        # 3. Assembler — collects all child elements in required order
        assembler = JMXAssembler()

        # 3a. JDBCDataSource (after UDV, before ThreadGroups)
        ds_gen = JDBCDataSourceGenerator(
            conn_config=self.test_config.conn_config.model_dump()
        )
        ds_elements = ds_gen.generate()
        assembler.add_many(ds_elements)

        # 3b. DDL SetupThreadGroup (if any DDL statements)
        ddl_elems = generate_ddl_setup_thread_group(self.ddl_statements)
        if ddl_elems:
            assembler.add_many(ddl_elems)

        # 3c. SharedMemory SetupThreadGroup (load CSV seed data into props)
        sm_elems = generate_shared_memory_setup_thread_group(self.seed_csv_paths)
        if sm_elems:
            assembler.add_many(sm_elems)

        # 3d. Write ThreadGroups (prepared modes only)
        write_elems = generate_write_thread_groups(
            self.test_config.write_config,
            self.prepared_templates,
        )
        if write_elems:
            assembler.add_many(write_elems)

        # 3e. Query ThreadGroups
        query_elems = generate_query_thread_groups(
            self.test_config.query_config,
        )
        if query_elems:
            assembler.add_many(query_elems)

        # 4. Assemble
        root = assembler.assemble(tp_elem, tp_hash, udv_elements)

        # 5. Write to file
        writer = JMXWriter(self.output_dir)
        return writer.write(root)
